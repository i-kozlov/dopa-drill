export function russianProblemText(value) {
  const text = String(value ?? '');
  if (!/[\u3040-\u30ff\u3400-\u9fff]/u.test(text)) return text;
  if (LABELS[text]) return LABELS[text];
  let out = text
    .replace(/^(\d+)のだん /u, '×$1: ')
    .replace(/^(\d+)の中に(\d+)はいくつ$/u, 'Сколько раз $2 помещается в $1?')
    .replace(/^(\d+)に いくつで (\d+)$/u, 'Сколько прибавить к $1, чтобы получить $2?')
    .replace(/^(\d+)に (\d+)で 10$/u, 'До десятка: $1 + $2')
    .replace(/^(\d+)を (\d+)つに わける$/u, '$1 ÷ $2')
    .replace(/^(\d+)をかける$/u, 'Умножь на $1')
    .replace(/^商の/u, 'Частное: ')
    .replace(/^くりあがりの /u, 'Перенос: ')
    .replace(/^たす（(.+)）$/u, 'Сложи ($1)')
    .replace(/^先に |^まず /u, 'Сначала ')
    .replace(/ の 10こぶん$/u, ' × 10')
    .replace(/ を 考える$/u, ' — вычисли')
    .replace(/ と 同じ$/u, ' — это то же самое')
    .replace(/^分母は (\d+) のまま$/u, 'Знаменатель $1 не меняется')
    .replace(/^通分すると 分母は (\d+)$/u, 'Общий знаменатель: $1')
    .replace(/^分子に (\d+) をかける$/u, 'Числитель умножь на $1')
    .replace(/^分母に (\d+) をかける$/u, 'Знаменатель умножь на $1')
    .replace(/ を ひっくりかえして かける$/u, ' — переверни дробь и умножь')
    .replace(/^(\d+)で わる$/u, 'Раздели на $1')
    .replace(/^(\d+)ばい$/u, 'Умножь на $1')
    .replace(/のばいすう$/u, ' — найди кратные')
    .replace(/の位を 四捨五入$/u, ' — округли')
    .replace(/の位まで$/u, ' разр.')
    .replace(/あまり/gu, 'ост.');
  for (const [ja, ru] of Object.entries(LABELS).sort((a, b) => b[0].length - a[0].length)) out = out.replaceAll(ja, ru);
  return out;
}
